        System.out.println("The Division Arithmetic Operation On Two Number Is = "+-20 / 4); // -5
        System.out.println("The Division Arithmetic Operation On Two Number Is = "+20 / -4); // -5
        System.out.println("The Division Arithmetic Operation On Two Number Is = "+20.0 / 2.5); // 8
