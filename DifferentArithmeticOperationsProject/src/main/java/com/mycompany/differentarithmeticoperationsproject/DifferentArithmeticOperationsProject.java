        System.out.println("The Addition Arithmetic Operation On Two Number Is = "+(20.45 + 10)); // 30.45
        System.out.println("The Addition Arithmetic Operation On Two Number Is = "+(10.23 + 5.45)); // 15.68
        System.out.println("The Subtraction Arithmetic Operation On Two Number Is = "+(20 - 10)); // 10
        System.out.println("The Subtraction Arithmetic Operation On Two Number Is = "+(10 - 20)); // -10
        System.out.println("The Subtraction Arithmetic Operation On Two Number Is = "+(10 - -20)); // 30
        System.out.println("The Subtraction Arithmetic Operation On Two Number Is = "+(-10 -20)); // -30
        System.out.println("The Subtraction Arithmetic Operation On Two Number Is = "+(-10 - -20)); // 10
        System.out.println("The Subtraction Arithmetic Operation On Two Number Is = "+(10.234 - 5.456)); // 4.778
        System.out.println("The Subtraction Arithmetic Operation On Two Number Is = "+(5.56 - 10.23)); // -4.6700
        System.out.println("The Multiplication Arithmetic Operation On Two Number Is = "+(4 * 5)); // 20
        System.out.println("The Multiplication Arithmetic Operation On Two Number Is = "+(-4 * 5)); // -20
        System.out.println("The Multiplication Arithmetic Operation On Two Number Is = "+-4 * -5); // 20
        System.out.println("The Multiplication Arithmetic Operation On Two Number Is = "+4 * -5); // -20
        System.out.println("The Multiplication Arithmetic Operation On Two Number Is = "+4.5 * 5.3); // 23.849
        System.out.println("The Multiplication Arithmetic Operation On Two Number Is = "+-4.5 * 5.3); // -23.849
        System.out.println("The Multiplication Arithmetic Operation On Two Number Is = "+4.5 * -5.3); // -23.849
        System.out.println("The Multiplication Arithmetic Operation On Two Number Is = "+-4.5 * -5.3); // 23.849
